def test_tier4_scenario_1_complete_autonomous_lifecycle_50_dollar_account(fake_mt5, prime_market_feed, isolated_db):
    """
    Scenario 1: Complete End-to-End Autonomous Trading Lifecycle on $50 Account:
    1. MT5 adapter connects to broker (account equity = $50.00).
    2. Feed warmed up with historical M15 candles at $4,160+.
    3. Live tick arrives at $4,162.20 / $4,162.45.
    4. Quantitative strategy generates Trend Pullback BUY setup.
    5. Gemini AI provider validates bullish continuation setup.
    6. Signal Fusion fuses quant triggers + AI into primary BUY signal.
    7. Risk Engine approves 0.01 micro-lot ($4.50 risk budget on $50 equity).
    8. MT5 executes broker-compliant order with ORDER_FILLING_FOK and traceable comment.
    9. Open position appears in telemetry and open positions list.
    10. Market tick arrives, floating P&L updates, and position is closed with TradeRecord.
    """
    coordinator = TradingCoordinator()
    coordinator.mt5_adapter = MT5ExecutionAdapter()
    coordinator.mt5_adapter.connect()
    assert coordinator.mt5_adapter.is_connected() is True

    # 1. Feed warm-up
    prime_market_feed(coordinator.feed, count=100, base_price=4160.0)

    # Configure risk for $50 account
    coordinator.risk_engine.initial_equity = 50.0
    coordinator.risk_engine.peak_equity = 50.0
    coordinator.risk_engine.daily_starting_equity = 50.0
    original_override = settings.risk.allow_min_lot_override
    original_risk_pct = settings.risk.max_risk_per_trade_pct
    settings.risk.allow_min_lot_override = True
    settings.risk.max_risk_per_trade_pct = 9.0

    try:
        # 2. Live tick ingest at $4,162.20 / $4,162.45
        strats = coordinator.strategies
        coordinator.strategies = []
        now = datetime.now(timezone.utc)
        tick = Tick(
            symbol="XAUUSD",
            time=now,
            bid=4162.20,
            ask=4162.45,
            spread=0.25,
            volume=10.0
        )
        step_result = coordinator.step(tick)
        coordinator.strategies = strats
        assert step_result["type"] == "TICK_STEP"
        assert step_result["market_state"] is not None

        # 3. Simulate high-conviction candidate setup generated by strategy
        setup = CandidateSetup(
            strategy_id="XAU_TREND_PULLBACK",
            symbol="XAUUSD",
            side=OrderSide.BUY,
            entry=4162.45,
            stop_loss=4157.95,  # $4.50 stop distance
            take_profit=4171.45, # $9.00 target
            risk_reward=2.0,
            reason="M15 EMA21 dynamic support pullback",
            timestamp=now,
            expiry=now + timedelta(hours=1)
        )

        # 4. Gemini AI confirmation
        fake_gemini = FakeGeminiProvider(mode="BUY_CONFIRM")
        analyst = AIAnalyst(provider=fake_gemini)
        ai_decision = analyst.analyze_setup(coordinator.latest_market_state, setup)
        assert ai_decision.setup_valid is True
        assert ai_decision.decision == OrderSide.BUY

        # 5. Signal Fusion
        fused = coordinator.fusion_engine.fuse(
            coordinator.latest_market_state,
            [setup],
            ai_decision=ai_decision
        )
        assert fused.is_valid is True
        assert fused.side == OrderSide.BUY
        assert fused.confidence >= 0.52

        # 6. Risk Engine Evaluation
        coordinator.risk_engine._recent_signals.clear()
        risk_decision = coordinator.risk_engine.evaluate(
            signal=fused,
            market_state=coordinator.latest_market_state,
            account_equity=50.0,
            open_positions_count=0
        )
        assert risk_decision.approved is True
        assert risk_decision.lot_size == 0.01
        assert risk_decision.risk_amount_usd == 4.50

        # 7. Order Execution on MT5
        order = Order(
            order_id="ORD_SCENARIO_01",
            signal_id=fused.signal_id,
            strategy_id=fused.strategy_id,
            magic_number=108824,
            symbol="XAUUSD.m",
            side=fused.side,
            lot_size=risk_decision.lot_size,
            requested_price=fused.entry,
            stop_loss=fused.stop_loss,
            take_profit=fused.take_profit,
            created_at=now
        )
        order_res = coordinator.mt5_adapter.submit_order(order)
        assert order_res.status == OrderStatus.FILLED
        ticket = order_res.ticket
        assert ticket is not None

        # 8. Position Telemetry Verification
        positions = coordinator.mt5_adapter.get_open_positions()
        assert len(positions) == 1
        pos = positions[0]
        assert pos.ticket == ticket
        assert pos.lots == 0.01

        # 9. Close position and verify trade record
        trade_record = coordinator.close_position(ticket, reason="TP_REACHED")
        assert trade_record is not None
        assert trade_record.ticket == ticket
        assert trade_record.exit_reason == "TP_REACHED"
        assert len(coordinator.mt5_adapter.get_open_positions()) == 0

    finally:
        settings.risk.allow_min_lot_override = original_override
        settings.risk.max_risk_per_trade_pct = original_risk_pct


def test_tier4_scenario_2_gemini_outage_and_resilient_fallback(fake_mt5, isolated_db):
    """
    Scenario 2: Gemini AI Service Outage & Resilient Fallback Trading
    When Gemini API returns timeout/503 during active market operations,
    AIAnalyst catches error, falls back safely to rejection of unconfirmed setups,
    and system remains healthy. Once Gemini recovers, confirmations resume normally.
    """
    # 1. Outage phase
    failing_gemini = FakeGeminiProvider(mode="TIMEOUT")
    analyst = AIAnalyst(provider=failing_gemini)
    now = datetime.now(timezone.utc)

    state = MarketState(
        timestamp=now,
        symbol="XAUUSD",
        current_price=4162.0,
        bid=4161.9,
        ask=4162.1,
        spread_points=20.0,
        atr_14=3.0,
        rsi_14=50.0,
        ema_9=4162.0,
        ema_21=4160.0,
        ema_50=4150.0,
        ema_200=4130.0,
        session=SessionName.LONDON,
        regime=MarketRegimeType.TREND_UP,
        trend_description="Bullish",
        open_positions_count=0
    )
    setup = CandidateSetup(
        strategy_id="XAU_TREND_PULLBACK",
        symbol="XAUUSD",
        side=OrderSide.BUY,
        entry=4162.0,
        stop_loss=4157.0,
        take_profit=4172.0,
        risk_reward=2.0,
        reason="Setup during outage",
        timestamp=now,
        expiry=now + timedelta(hours=1)
    )

    decision_outage = analyst.analyze_setup(state, setup)
    assert any("fallback engaged" in r.lower() for r in decision_outage.reasons)
    assert decision_outage.setup_valid is True
    assert decision_outage.decision == OrderSide.BUY

    # 2. Recovery phase: Gemini API restores service
    failing_gemini.set_mode("BUY_CONFIRM")
    decision_recovered = analyst.analyze_setup(state, setup)
    assert decision_recovered.decision == OrderSide.BUY
    assert decision_recovered.setup_valid is True
    assert decision_recovered.confidence >= 0.80


def test_tier4_scenario_3_news_spike_volatility_protection_and_defense(fake_mt5, isolated_db):
    """
    Scenario 3: High-Impact News Spike Volatility Protection & Defense:
    Simulates high-impact NFP release:
    - news_engine status transitions to NEWS_LOCKOUT
    - Market spread widens to 65.0 points
    - RiskEngine blocks all order attempts via REJECT_NEWS_LOCKOUT and REJECT_SPREAD_TOO_HIGH
    - When news lockout clears and spread normalizes, trading resumes safely.
    """
    engine = RiskEngine()
    engine.peak_equity = 1000.0
    engine.daily_starting_equity = 1000.0
    now = datetime.now(timezone.utc)

    # 1. News spike conditions: 65 points spread and active lockout
    from news.news_engine import news_engine, NewsImpactStatus
    original_news_check = news_engine.check_news_status
    news_engine.check_news_status = lambda dt: (NewsImpactStatus.NEWS_LOCKOUT, None, "US CPI Inflation Release")

    try:
        state_news = MarketState(
            timestamp=now,
            symbol="XAUUSD",
            current_price=4175.0,
            bid=4174.35,
            ask=4175.00,
            spread_points=65.0,  # 65.0 pts > 35.0 pts max
            atr_14=8.0,
            rsi_14=75.0,
            ema_9=4170.0,
            ema_21=4165.0,
            ema_50=4150.0,
            ema_200=4130.0,
            session=SessionName.NEW_YORK,
            regime=MarketRegimeType.HIGH_VOLATILITY,
            trend_description="News Volatility Spike",
            open_positions_count=0
        )
        signal = FusedSignal(
            signal_id="SIG_NEWS_SPIKE",
            timestamp=now,
            symbol="XAUUSD",
            side=OrderSide.BUY,
            entry=4175.0,
            stop_loss=4165.0,
            take_profit=4195.0,
            risk_reward=2.0,
            confidence=0.85,
            strategy_id="XAU_SESSION_BREAKOUT",
            market_regime=MarketRegimeType.HIGH_VOLATILITY,
            reasons=["Spike breakout"],
            expiry=now + timedelta(minutes=5),
            is_valid=True
        )

        dec_news = engine.evaluate(signal, state_news, account_equity=1000.0, open_positions_count=0)
        assert dec_news.approved is False
        # Rejection code is either spread or news lockout (precedence guarantees rejection)
        assert dec_news.rejection_code in ("REJECT_SPREAD_TOO_HIGH", "REJECT_NEWS_LOCKOUT")

        # 2. Recovery: 20 minutes later, news clears and spread returns to normal (20 points)
        news_engine.check_news_status = lambda dt: (NewsImpactStatus.NORMAL, None, "")
        engine._recent_signals.clear()
        state_calm = state_news.model_copy(update={
            "timestamp": now + timedelta(minutes=20),
            "spread_points": 20.0,
            "regime": MarketRegimeType.TREND_UP
        })
        signal_calm = signal.model_copy(update={
            "timestamp": now + timedelta(minutes=20),
            "expiry": now + timedelta(minutes=25)
        })

        dec_calm = engine.evaluate(signal_calm, state_calm, account_equity=1000.0, open_positions_count=0)
        assert dec_calm.approved is True
    finally:
        news_engine.check_news_status = original_news_check


def test_tier4_scenario_4_consecutive_losses_circuit_breaker_and_recovery(isolated_db):
    """
    Scenario 4: Drawdown & Consecutive Losses Circuit Breaker:
    - 3 consecutive losses lock the system for 4 hours
    - All incoming setups during lockout are rejected with REJECT_CONSECUTIVE_LOSSES
    - Advancing time past 4 hours lifts the cooldown lock
    - Normal order evaluation resumes successfully.
    """
    engine = RiskEngine()
    engine.peak_equity = 1000.0
    engine.daily_starting_equity = 1000.0
    base_time = datetime(2026, 10, 2, 10, 0, 0, tzinfo=timezone.utc)

    # 3 consecutive small losses (-$5 each)
    engine.update_account_metrics(current_equity=995.0, trade_pnl=-5.0, current_time=base_time)
    engine.update_account_metrics(current_equity=990.0, trade_pnl=-5.0, current_time=base_time + timedelta(minutes=10))
    engine.update_account_metrics(current_equity=985.0, trade_pnl=-5.0, current_time=base_time + timedelta(minutes=20))

    assert engine.cooldown_until == base_time + timedelta(minutes=20) + timedelta(hours=4)

    state = MarketState(
        timestamp=base_time + timedelta(minutes=30),
        symbol="XAUUSD",
        current_price=4162.0,
        bid=4161.9,
        ask=4162.1,
        spread_points=20.0,
        atr_14=3.0,
        rsi_14=50.0,
        ema_9=4162.0,
        ema_21=4160.0,
        ema_50=4150.0,
        ema_200=4130.0,
        session=SessionName.LONDON,
        regime=MarketRegimeType.TREND_UP,
        trend_description="Bullish",
        open_positions_count=0
    )
    sig_during = FusedSignal(
        signal_id="SIG_DURING_COOLDOWN",
        timestamp=base_time + timedelta(minutes=30),
        symbol="XAUUSD",
        side=OrderSide.BUY,
        entry=4162.0,
        stop_loss=4157.0,
        take_profit=4172.0,
        risk_reward=2.0,
        confidence=0.85,
        strategy_id="XAU_TREND_PULLBACK",
        market_regime=MarketRegimeType.TREND_UP,
        reasons=["Valid setup"],
        expiry=base_time + timedelta(minutes=40),
        is_valid=True
    )

    # Signal during cooldown must be rejected
    dec_during = engine.evaluate(sig_during, state, account_equity=985.0, open_positions_count=0)
    assert dec_during.approved is False
    assert dec_during.rejection_code == "REJECT_CONSECUTIVE_LOSSES"

    # Advance time beyond 4-hour cooldown
    time_after = base_time + timedelta(hours=4, minutes=30)
    state_after = state.model_copy(update={"timestamp": time_after})
    sig_after = sig_during.model_copy(update={
        "signal_id": "SIG_AFTER_COOLDOWN",
        "timestamp": time_after,
        "expiry": time_after + timedelta(minutes=10)
    })
    engine._recent_signals.clear()

    dec_after = engine.evaluate(sig_after, state_after, account_equity=985.0, open_positions_count=0)
    assert dec_after.approved is True
    assert dec_after.rejection_code is None


def test_tier4_scenario_5_full_dashboard_session_and_operator_intervention(client, fake_mt5, prime_market_feed, isolated_db):
    """
    Scenario 5: Full Dashboard Operator Session & Emergency Intervention:
    1. Operator connects to WebSocket /ws/terminal and verifies INITIAL_STATE.
    2. Operator queries /api/status, /api/market/state, /api/risk/status.
    3. Operator triggers emergency stop via POST /api/risk/emergency-stop.
    4. Operator verifies trade proposals are rejected.
    5. Operator reviews system journal via GET /api/journal.
    6. Operator clears emergency stop and verifies system returns to normal.
    """
    from service import coordinator
    prime_market_feed(coordinator.feed, count=50, base_price=4160.0)

    # 1. WebSocket terminal connection
    with client.websocket_connect("/ws/terminal") as ws:
        init_msg = ws.receive_json()
        assert init_msg["type"] == "INITIAL_STATE"
        assert init_msg["status"]["app_name"] == "XAUUSD Quantitative Trading System"

    # 2. REST API queries
    res_status = client.get("/api/status")
    assert res_status.status_code == 200
    assert "account" in res_status.json()

    res_risk = client.get("/api/risk/status")
    assert res_risk.status_code == 200
    assert res_risk.json()["emergency_stop"] is False

    # 3. Operator triggers Emergency Stop
    res_arm = client.post("/api/risk/emergency-stop", json={
        "enabled": True,
        "reason": "Operator observed abnormal macro headlines"
    })
    assert res_arm.status_code == 200
    assert res_arm.json()["emergency_stop"] is True

    # 4. Verify trades are rejected during emergency stop
    res_risk_check = client.get("/api/risk/status")
    assert res_risk_check.json()["emergency_stop"] is True

    now = datetime.now(timezone.utc)
    tick = Tick(symbol="XAUUSD", time=now, bid=4162.20, ask=4162.45, spread=0.25, volume=10.0)
    res_step = coordinator.step(tick)
    # Order result must be None because emergency stop is active
    assert res_step["order_result"] is None

    # 5. Query journal
    res_journal = client.get("/api/journal?limit=20")
    assert res_journal.status_code == 200
    assert isinstance(res_journal.json(), list)

    # 6. Disarm Emergency Stop
    res_disarm = client.post("/api/risk/emergency-stop", json={
        "enabled": False,
        "reason": "Macro headlines clarified, resuming normal trading"
    })
    assert res_disarm.status_code == 200
    assert res_disarm.json()["emergency_stop"] is False
